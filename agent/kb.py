"""
Knowledge base: drop PDFs (CUDA programming guide, tuning guides, papers) and docs into knowledge/, then search them.

    ./optk kb add path/to/guide.pdf          copy a PDF/markdown/text file in (or: put it in knowledge/pdfs/ yourself)
    ./optk kb add https://.../page.html      download a PDF, or an HTML page converted to text
    ./optk kb ingest                         extract text from anything new or changed (also done lazily by search)
    ./optk kb list
    ./optk kb search "bank conflicts shared memory" [-n 6] [--doc slug]
    ./optk kb read <slug> --pages 12-14      print extracted pages (a 'page' of a text doc is a ~3000-char chunk)

Layout: knowledge/pdfs/ (PDFs), knowledge/docs/ (md/txt/converted web pages), knowledge/hardware/ (short GPU notes),
knowledge/resources.md (curated links). Extracted text is cached under knowledge/.cache/ (derived, gitignored).
Search is BM25 over pages, pure Python, so there are no dependencies beyond pypdf for PDFs.
"""
import argparse
import html
import json
import math
import re
import shutil
import subprocess
import sys
import urllib.request
from collections import Counter
from html.parser import HTMLParser
from pathlib import Path

from . import config

KB = config.KNOWLEDGE
CACHE = KB / ".cache"
EXTS = {".pdf", ".md", ".txt"}
SKIP = {"README.md", "INDEX.md"}
CHUNK = 3000
MAX_READ_CHARS = 14000


def slugify(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:60] or "doc"


def sources() -> list[Path]:
    out = []
    for p in sorted(KB.rglob("*")):
        if p.is_file() and p.suffix.lower() in EXTS and p.name not in SKIP and ".cache" not in p.parts:
            out.append(p)
    return out


def _slug_for(p: Path, taken: set[str]) -> str:
    s = slugify(p.stem)
    if "problems" in p.relative_to(KB).parts[:-2] + p.relative_to(KB).parts[:1]:      # knowledge/problems/<name>/notes.md -> moe-notes
        s = slugify(f"{p.parent.name}-{p.stem}")
    if s in taken:
        s = slugify(f"{p.parent.name}-{p.stem}")
    taken.add(s)
    return s


def _pdf_pages(p: Path) -> tuple[str, list[str]]:
    title = ""
    if shutil.which("pdftotext"):
        r = subprocess.run(["pdftotext", "-layout", str(p), "-"], capture_output=True, text=True)
        if r.returncode == 0 and r.stdout.strip():
            pages = r.stdout.split("\f")
            if pages and not pages[-1].strip():
                pages.pop()
            return title, pages
    try:
        from pypdf import PdfReader
    except ImportError:
        raise SystemExit("reading PDFs needs pypdf (pip install pypdf) or poppler's pdftotext")
    rd = PdfReader(str(p))
    if rd.is_encrypted:
        try:
            rd.decrypt("")
        except Exception:
            raise SystemExit(f"{p.name} is encrypted")
    try:
        title = (rd.metadata.title or "") if rd.metadata else ""
    except Exception:
        pass
    pages = []
    for pg in rd.pages:
        try:
            pages.append(pg.extract_text() or "")
        except Exception:
            pages.append("")
    return title, pages


def _chunks(text: str, size: int = CHUNK) -> list[str]:
    paras = re.split(r"\n\s*\n", text)
    out, cur = [], ""
    for para in paras:
        if cur and len(cur) + len(para) > size:
            out.append(cur)
            cur = ""
        cur += para + "\n\n"
    if cur.strip():
        out.append(cur)
    return out or [""]


def extract(p: Path) -> dict:
    if p.suffix.lower() == ".pdf":
        title, pages = _pdf_pages(p)
    else:
        text = p.read_text(errors="replace")
        title, pages = "", _chunks(text)
    if not title:
        first = next((l.strip() for pg in pages[:3] for l in pg.splitlines() if len(l.strip()) > 3), p.stem)
        title = first[:100]
    st = p.stat()
    return {"source": str(p.relative_to(KB)), "size": st.st_size, "mtime": st.st_mtime, "title": title, "pages": pages}


def ingest(force: bool = False, log=print) -> list[dict]:
    CACHE.mkdir(parents=True, exist_ok=True)
    docs, taken = [], set()
    live = set()
    for p in sources():
        slug = _slug_for(p, taken)
        live.add(slug)
        cf = CACHE / f"{slug}.json"
        st = p.stat()
        if cf.exists() and not force:
            d = json.loads(cf.read_text())
            if d["size"] == st.st_size and d["mtime"] == st.st_mtime:
                docs.append({**d, "slug": slug})
                continue
        log(f"ingesting {p.relative_to(KB)} ...")
        d = extract(p)
        cf.write_text(json.dumps(d))
        docs.append({**d, "slug": slug})
        log(f"  {len(d['pages'])} pages")
    for cf in CACHE.glob("*.json"):       # a source that was deleted
        if cf.stem not in live:
            cf.unlink()
    write_index(docs)
    return docs


def write_index(docs: list[dict]):
    lines = ["# Knowledge base index", "", "Generated by `./optk kb ingest`. Search with `./optk kb search \"...\"`.", "",
             "| slug | pages | title | file |", "|---|---:|---|---|"]
    for d in docs:
        lines.append(f"| {d['slug']} | {len(d['pages'])} | {d['title'].replace('|', '/')} | {d['source']} |")
    (KB / "INDEX.md").write_text("\n".join(lines) + "\n")


def list_docs() -> list[dict]:
    CACHE.mkdir(parents=True, exist_ok=True)
    try:
        return ingest(log=lambda *_: None)
    except SystemExit:
        return []


# ---- search ---------------------------------------------------------------------------------------
_TOK = re.compile(r"[a-z0-9_]+")


def tokens(s: str) -> list[str]:
    out = []
    for t in _TOK.findall(s.lower()):
        out.append(t[:-1] if len(t) > 3 and t.endswith("s") and not t.endswith("ss") else t)
    return out


def search(query: str, n: int = 6, doc: str | None = None) -> list[dict]:
    docs = [d for d in ingest(log=lambda *_: None) if not doc or d["slug"] == doc]
    q = [t for t in tokens(query) if len(t) > 1]
    if not q:
        return []
    pages = [(d, i, pg, Counter(tokens(pg))) for d in docs for i, pg in enumerate(d["pages"], start=1)]
    N = len(pages) or 1
    df = Counter(t for *_, c in pages for t in set(c) if t in set(q))
    avg = sum(sum(c.values()) for *_, c in pages) / N or 1
    k1, b = 1.5, 0.75
    scored = []
    for d, i, pg, c in pages:
        ln = sum(c.values()) or 1
        s = 0.0
        for t in set(q):
            f = c.get(t, 0)
            if f:
                idf = math.log(1 + (N - df[t] + 0.5) / (df[t] + 0.5))
                s += idf * f * (k1 + 1) / (f + k1 * (1 - b + b * ln / avg))
        if s > 0:
            scored.append((s, d, i, pg))
    scored.sort(key=lambda x: -x[0])
    return [{"score": s, "slug": d["slug"], "page": i, "title": d["title"], "snippet": snippet(pg, q)}
            for s, d, i, pg in scored[:n]]


def snippet(page: str, q: list[str], width: int = 6) -> str:
    lines = [l for l in page.splitlines() if l.strip()]
    if not lines:
        return ""
    qs = set(q)
    best, best_i = -1, 0
    for i in range(max(1, len(lines) - width + 1)):
        window = lines[i:i + width]
        score = len(qs & set(tokens(" ".join(window))))
        if score > best:
            best, best_i = score, i
    text = " ".join(l.strip() for l in lines[best_i:best_i + width])
    return text[:420] + ("…" if len(text) > 420 else "")


# ---- add ------------------------------------------------------------------------------------------
class _Text(HTMLParser):
    SKIP = {"script", "style", "nav", "header", "footer", "noscript", "svg", "form"}
    BLOCK = {"p", "div", "section", "article", "li", "tr", "br", "pre", "table", "ul", "ol", "blockquote"}

    def __init__(self):
        super().__init__()
        self.out, self.skip = [], 0

    def handle_starttag(self, tag, attrs):
        if tag in self.SKIP:
            self.skip += 1
        elif re.fullmatch(r"h[1-6]", tag):
            self.out.append("\n\n" + "#" * int(tag[1]) + " ")
        elif tag in self.BLOCK:
            self.out.append("\n")

    def handle_endtag(self, tag):
        if tag in self.SKIP and self.skip:
            self.skip -= 1
        elif re.fullmatch(r"h[1-6]", tag) or tag in self.BLOCK:
            self.out.append("\n")

    def handle_data(self, data):
        if not self.skip:
            self.out.append(data)


def html_to_text(raw: str) -> tuple[str, str]:
    m = re.search(r"<title[^>]*>(.*?)</title>", raw, re.S | re.I)
    p = _Text()
    p.feed(raw)
    text = html.unescape("".join(p.out))
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"\n\s*\n\s*\n+", "\n\n", text).strip()
    return (html.unescape(m.group(1)).strip() if m else ""), text


def add(src: str, name: str | None = None, log=print) -> Path:
    (KB / "pdfs").mkdir(parents=True, exist_ok=True)
    (KB / "docs").mkdir(parents=True, exist_ok=True)
    if re.match(r"https?://", src):
        req = urllib.request.Request(src, headers={"User-Agent": "optk-kb/1.0"})
        with urllib.request.urlopen(req, timeout=60) as r:
            data, ctype = r.read(), r.headers.get("Content-Type", "")
        stem = slugify(name or Path(re.sub(r"[?#].*", "", src)).stem or "page")
        if data[:5] == b"%PDF-" or "pdf" in ctype:
            dest = KB / "pdfs" / f"{stem}.pdf"
            dest.write_bytes(data)
        else:
            title, text = html_to_text(data.decode("utf-8", "replace"))
            dest = KB / "docs" / f"{stem}.md"
            dest.write_text(f"# {title or stem}\n\nsource: {src}\n\n{text}\n")
    else:
        p = Path(src).expanduser()
        if not p.is_file():
            raise SystemExit(f"{src}: no such file")
        if p.suffix.lower() not in EXTS:
            raise SystemExit(f"unsupported file type {p.suffix} (pdf, md, txt)")
        dest = KB / ("pdfs" if p.suffix.lower() == ".pdf" else "docs") / (slugify(name) + p.suffix.lower() if name else p.name)
        shutil.copy2(p, dest)
    log(f"added {dest.relative_to(KB)}")
    ingest(log=log)
    return dest


# ---- cli ------------------------------------------------------------------------------------------
def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="optk kb", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list")
    p = sub.add_parser("ingest")
    p.add_argument("--force", action="store_true")
    p = sub.add_parser("search")
    p.add_argument("query", nargs="+")
    p.add_argument("-n", type=int, default=6)
    p.add_argument("--doc")
    p = sub.add_parser("read")
    p.add_argument("slug")
    p.add_argument("--pages", help="e.g. 12 or 12-14 (default: 1)")
    p = sub.add_parser("add")
    p.add_argument("source", help="file path or URL")
    p.add_argument("--name")
    a = ap.parse_args(argv)

    if a.cmd == "ingest":
        docs = ingest(force=a.force)
        print(f"{len(docs)} documents, {sum(len(d['pages']) for d in docs)} pages -> knowledge/INDEX.md")
    elif a.cmd == "list":
        docs = ingest(log=lambda *_: None)
        if not docs:
            print("(empty) put PDFs in knowledge/pdfs/ or run: ./optk kb add <file-or-url>")
        for d in docs:
            print(f"{d['slug']:<40} {len(d['pages']):>5} pages  {d['title'][:60]}")
    elif a.cmd == "search":
        hits = search(" ".join(a.query), a.n, a.doc)
        if not hits:
            print("no matches (try fewer or different words; ./optk kb list shows what is indexed)")
        for i, h in enumerate(hits, 1):
            print(f"{i}. [{h['slug']} p.{h['page']}] {h['title'][:50]}  (score {h['score']:.1f})\n   {h['snippet']}")
        if hits:
            print("\nread more: ./optk kb read <slug> --pages N-M")
    elif a.cmd == "read":
        doc = next((d for d in ingest(log=lambda *_: None) if d["slug"] == a.slug), None)
        if not doc:
            raise SystemExit(f"unknown document '{a.slug}' (./optk kb list)")
        lo, _, hi = (a.pages or "1").partition("-")
        lo, hi = int(lo), int(hi or lo)
        text = ""
        for i in range(lo, min(hi, len(doc["pages"])) + 1):
            text += f"\n===== {doc['slug']} page {i}/{len(doc['pages'])} =====\n{doc['pages'][i - 1]}"
        print(text[:MAX_READ_CHARS] + ("\n... (truncated; read fewer pages)" if len(text) > MAX_READ_CHARS else ""))
    elif a.cmd == "add":
        add(a.source, a.name)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
